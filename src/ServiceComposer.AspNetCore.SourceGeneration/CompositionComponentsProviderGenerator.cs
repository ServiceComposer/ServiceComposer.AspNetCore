using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace ServiceComposer.AspNetCore.SourceGeneration;

/// <summary>
/// Generates an <c>ICompositionComponentsProvider</c> implementation that registers
/// the composition components defined in the assembly being compiled, the same ones
/// assembly scanning would find, without using reflection at runtime. It also generates
/// a <c>RegisterReferencedComponents()</c> extension method that registers that provider
/// and the providers of all referenced assemblies.
/// </summary>
[Generator]
public class CompositionComponentsProviderGenerator : IIncrementalGenerator
{
    internal const string ProviderClassName = "GeneratedCompositionComponentsProvider";
    internal const string RegistrationClassName = "GeneratedReferencedComponentsRegistration";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Contract-less handlers: the wrappers generated by the CompositionHandlerWrapperGenerator
        // are not visible to this generator, so their names are computed the same way.
        var contractlessHandlerMethods = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => CompositionHandlerWrapperGenerator.IsCompositionHandlerMethod(node),
                transform: static (ctx, _) => CompositionHandlerWrapperGenerator.GetCompositionHandlerMethod(ctx))
            .Where(static m => m is not null)
            .Select(static (m, _) => m!);

        var compilationAndMethods = context.CompilationProvider.Combine(contractlessHandlerMethods.Collect());

        context.RegisterSourceOutput(compilationAndMethods,
            static (spc, source) => Execute(spc, source.Left, source.Right));
    }

    sealed class KnownTypes
    {
        public INamedTypeSymbol ComponentsProvider = null!;
        public INamedTypeSymbol ProviderAttribute = null!;
        public INamedTypeSymbol RequestsHandler = null!;
        public INamedTypeSymbol EventsSubscriber = null!;
        public INamedTypeSymbol EventsHandler = null!;
        public INamedTypeSymbol PreviewHandler = null!;
        public INamedTypeSymbol ViewModelFactory = null!;
        public INamedTypeSymbol EndpointScopedViewModelFactory = null!;
        public INamedTypeSymbol RequestFilter = null!;
        public INamedTypeSymbol GenericRequestFilter = null!;
        public INamedTypeSymbol OptionsCustomization = null!;
        public INamedTypeSymbol CompositionHandlerAttribute = null!;
        public INamedTypeSymbol Attribute = null!;

        public static KnownTypes? Resolve(Compilation compilation)
        {
            INamedTypeSymbol? Get(string name) => compilation.GetTypeByMetadataName(name);

            const string ns = "ServiceComposer.AspNetCore.";
            var componentsProvider = Get(ns + "ICompositionComponentsProvider");
            var providerAttribute = Get(ns + "CompositionComponentsProviderAttribute");
            var requestsHandler = Get(ns + "ICompositionRequestsHandler");
            var eventsSubscriber = Get(ns + "ICompositionEventsSubscriber");
            var eventsHandler = Get(ns + "ICompositionEventsHandler`1");
            var previewHandler = Get(ns + "IViewModelPreviewHandler");
            var viewModelFactory = Get(ns + "IViewModelFactory");
            var endpointScopedViewModelFactory = Get(ns + "IEndpointScopedViewModelFactory");
            var requestFilter = Get(ns + "ICompositionRequestFilter");
            var genericRequestFilter = Get(ns + "ICompositionRequestFilter`1");
            var optionsCustomization = Get(ns + "IViewModelCompositionOptionsCustomization");
            var compositionHandlerAttribute = Get(ns + "CompositionHandlerAttribute");
            var attribute = Get("System.Attribute");

            // Compiling against a ServiceComposer version that doesn't support
            // components providers, or not referencing ServiceComposer at all.
            if (componentsProvider is null || providerAttribute is null || requestsHandler is null
                || eventsSubscriber is null || eventsHandler is null || previewHandler is null
                || viewModelFactory is null || endpointScopedViewModelFactory is null || requestFilter is null
                || genericRequestFilter is null || optionsCustomization is null
                || compositionHandlerAttribute is null || attribute is null)
            {
                return null;
            }

            return new KnownTypes
            {
                ComponentsProvider = componentsProvider,
                ProviderAttribute = providerAttribute,
                RequestsHandler = requestsHandler,
                EventsSubscriber = eventsSubscriber,
                EventsHandler = eventsHandler,
                PreviewHandler = previewHandler,
                ViewModelFactory = viewModelFactory,
                EndpointScopedViewModelFactory = endpointScopedViewModelFactory,
                RequestFilter = requestFilter,
                GenericRequestFilter = genericRequestFilter,
                OptionsCustomization = optionsCustomization,
                CompositionHandlerAttribute = compositionHandlerAttribute,
                Attribute = attribute
            };
        }
    }

    static void Execute(SourceProductionContext context, Compilation compilation, ImmutableArray<CompositionHandlerMethodInfo> contractlessHandlerMethods)
    {
        try
        {
            var knownTypes = KnownTypes.Resolve(compilation);
            if (knownTypes is null || string.IsNullOrEmpty(compilation.AssemblyName))
            {
                return;
            }

            var customizations = new List<string>();
            var registrations = new List<string>();

            foreach (var type in GetCandidateTypes(compilation))
            {
                context.CancellationToken.ThrowIfCancellationRequested();
                Classify(type, knownTypes, customizations, registrations);
            }

            foreach (var wrapper in GetContractlessHandlerWrappers(compilation, contractlessHandlerMethods))
            {
                registrations.Add($"options.RegisterCompositionHandler<{wrapper}>();");
            }

            var providers = GetReferencedProviders(compilation, knownTypes);

            if (customizations.Count > 0 || registrations.Count > 0)
            {
                var providerNamespace = ToNamespace(compilation.AssemblyName!);
                var source = GenerateProvider(providerNamespace, customizations, registrations);
                context.AddSource($"{ProviderClassName}.g.cs", SourceText.From(source, Encoding.UTF8));

                providers.Add($"global::{providerNamespace}.{ProviderClassName}");
            }

            if (providers.Count > 0)
            {
                var source = GenerateReferencedComponentsRegistration(providers);
                context.AddSource($"{RegistrationClassName}.g.cs", SourceText.From(source, Encoding.UTF8));
            }
        }
        catch (OperationCanceledException)
        {
            throw;
        }
        catch (Exception ex)
        {
            context.ReportDiagnostic(
                Diagnostic.Create(
                    new DiagnosticDescriptor(
                        "SC003",
                        "Components provider generation failed",
                        "Generating the composition components provider failed: {0}",
                        "CodeGeneration",
                        DiagnosticSeverity.Error,
                        true
                    ),
                    Location.None,
                    ex.ToString()
                )
            );
        }
    }

    /// <summary>
    /// The providers of the referenced assemblies, identified by the
    /// CompositionComponentsProviderAttribute their generated code applies.
    /// </summary>
    static List<string> GetReferencedProviders(Compilation compilation, KnownTypes knownTypes)
    {
        var providers = new List<string>();
        foreach (var assembly in compilation.SourceModule.ReferencedAssemblySymbols)
        {
            foreach (var attribute in assembly.GetAttributes())
            {
                if (SymbolEqualityComparer.Default.Equals(attribute.AttributeClass, knownTypes.ProviderAttribute)
                    && attribute.ConstructorArguments.Length == 1
                    && attribute.ConstructorArguments[0].Value is INamedTypeSymbol providerType
                    && providerType.AllInterfaces.Any(i => SymbolEqualityComparer.Default.Equals(i, knownTypes.ComponentsProvider))
                    && compilation.IsSymbolAccessibleWithin(providerType, compilation.Assembly))
                {
                    providers.Add(providerType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
                }
            }
        }

        return providers;
    }

    static IEnumerable<INamedTypeSymbol> GetCandidateTypes(Compilation compilation)
    {
        var stack = new Stack<INamespaceOrTypeSymbol>();
        stack.Push(compilation.Assembly.GlobalNamespace);
        while (stack.Count > 0)
        {
            var current = stack.Pop();
            foreach (var member in current.GetMembers())
            {
                if (member is INamespaceSymbol ns)
                {
                    stack.Push(ns);
                }
                else if (member is INamedTypeSymbol type)
                {
                    stack.Push(type);

                    // Same rules as assembly scanning: concrete classes only. On top of that, the
                    // provider can only register types it can reference: open generic types and
                    // types not accessible at the assembly level (e.g., private nested classes)
                    // are skipped.
                    if (type.TypeKind == TypeKind.Class
                        && !type.IsAbstract
                        && !type.IsStatic
                        && !type.IsImplicitlyDeclared
                        && !IsOrIsNestedInGenericType(type)
                        && compilation.IsSymbolAccessibleWithin(type, compilation.Assembly))
                    {
                        yield return type;
                    }
                }
            }
        }
    }

    static bool IsOrIsNestedInGenericType(INamedTypeSymbol type)
    {
        for (var current = type; current != null; current = current.ContainingType)
        {
            if (current.IsGenericType)
            {
                return true;
            }
        }

        return false;
    }

    static void Classify(INamedTypeSymbol type, KnownTypes knownTypes, List<string> customizations, List<string> registrations)
    {
        var typeName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var interfaces = type.AllInterfaces;

        bool Implements(INamedTypeSymbol @interface) =>
            interfaces.Any(i => SymbolEqualityComparer.Default.Equals(i, @interface));

        bool ImplementsGeneric(INamedTypeSymbol genericInterface) =>
            interfaces.Any(i => SymbolEqualityComparer.Default.Equals(i.OriginalDefinition, genericInterface));

        if (Implements(knownTypes.OptionsCustomization) && HasAccessibleParameterlessConstructor(type))
        {
            customizations.Add($"new {typeName}().Customize(options);");
        }

        var isContractlessHandler = type.GetAttributes()
            .Any(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, knownTypes.CompositionHandlerAttribute));

        if (Implements(knownTypes.RequestsHandler)
            || Implements(knownTypes.EventsSubscriber)
            || ImplementsGeneric(knownTypes.EventsHandler)
            || Implements(knownTypes.EndpointScopedViewModelFactory)
            || isContractlessHandler)
        {
            registrations.Add($"options.RegisterCompositionHandler<{typeName}>();");
        }

        if (Implements(knownTypes.ViewModelFactory) && !Implements(knownTypes.EndpointScopedViewModelFactory))
        {
            registrations.Add($"options.RegisterGlobalViewModelFactory<{typeName}>();");
        }

        if (Implements(knownTypes.PreviewHandler))
        {
            var previewHandler = knownTypes.PreviewHandler.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            registrations.Add($"{AddTransient}<{previewHandler}, {typeName}>(options.Services);");
        }

        // Filters applied through attributes are not registered in the container.
        if (Implements(knownTypes.RequestFilter) && !InheritsFrom(type, knownTypes.Attribute))
        {
            foreach (var filterInterface in interfaces.Where(i => SymbolEqualityComparer.Default.Equals(i.OriginalDefinition, knownTypes.GenericRequestFilter)))
            {
                var filterInterfaceName = filterInterface.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                registrations.Add($"{AddTransient}<{filterInterfaceName}, {typeName}>(options.Services);");
            }
        }
    }

    const string AddTransient = "global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddTransient";

    static bool HasAccessibleParameterlessConstructor(INamedTypeSymbol type) =>
        type.InstanceConstructors.Any(c => c.Parameters.Length == 0
                                           && c.DeclaredAccessibility is Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedOrInternal);

    static bool InheritsFrom(INamedTypeSymbol type, INamedTypeSymbol baseType)
    {
        for (var current = type.BaseType; current != null; current = current.BaseType)
        {
            if (SymbolEqualityComparer.Default.Equals(current, baseType))
            {
                return true;
            }
        }

        return false;
    }

    static IEnumerable<string> GetContractlessHandlerWrappers(Compilation compilation, ImmutableArray<CompositionHandlerMethodInfo> methods)
    {
        var wrappers = new List<string>();
        foreach (var method in methods)
        {
            // Methods with more than one Http* attribute are reported
            // as errors by the wrapper generator and get no wrapper.
            if (method.HttpAttributes.Length != 1)
            {
                continue;
            }

            var semanticModel = compilation.GetSemanticModel(method.Method.SyntaxTree);
            var wrapperNamespace = CompositionHandlerWrapperGenerator.GetWrapperNamespace(method);
            var wrapperClassName = CompositionHandlerWrapperGenerator.GetWrapperClassName(semanticModel, method);
            wrappers.Add($"global::{wrapperNamespace}.{wrapperClassName}");
        }

        return wrappers.Distinct();
    }

    /// <summary>
    /// The generated provider lives in a namespace named after the assembly, so that
    /// providers generated in different assemblies never clash in the host.
    /// </summary>
    internal static string ToNamespace(string assemblyName)
    {
        var segments = assemblyName.Split('.')
            .Where(segment => segment.Length > 0)
            .Select(segment =>
            {
                var builder = new StringBuilder();
                foreach (var c in segment)
                {
                    builder.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
                }

                var identifier = builder.ToString();
                if (char.IsDigit(identifier[0]))
                {
                    identifier = "_" + identifier;
                }

                return SyntaxFacts.GetKeywordKind(identifier) != SyntaxKind.None
                    ? "@" + identifier
                    : identifier;
            });

        return string.Join(".", segments);
    }

    static string GenerateProvider(string providerNamespace, List<string> customizations, List<string> registrations)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#pragma warning disable CS0612, CS0618, SC0001");
        builder.AppendLine();
        builder.AppendLine($"[assembly: global::ServiceComposer.AspNetCore.CompositionComponentsProviderAttribute(typeof(global::{providerNamespace}.{ProviderClassName}))]");
        builder.AppendLine();
        builder.AppendLine($"namespace {providerNamespace}");
        builder.AppendLine("{");
        builder.AppendLine("    /// <summary>");
        builder.AppendLine("    /// Registers the composition components defined in this assembly.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine($"    public sealed class {ProviderClassName} : global::ServiceComposer.AspNetCore.ICompositionComponentsProvider");
        builder.AppendLine("    {");
        AppendMethod(builder, "Customize", customizations);
        builder.AppendLine();
        AppendMethod(builder, "RegisterComponents", registrations);
        builder.AppendLine("    }");
        builder.AppendLine("}");
        builder.AppendLine("#pragma warning restore CS0612, CS0618, SC0001");

        return builder.ToString();
    }

    static string GenerateReferencedComponentsRegistration(List<string> providers)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("namespace ServiceComposer.AspNetCore");
        builder.AppendLine("{");
        builder.AppendLine($"    internal static class {RegistrationClassName}");
        builder.AppendLine("    {");
        builder.AppendLine("        /// <summary>");
        builder.AppendLine("        /// Registers the composition components of this assembly and of all the referenced");
        builder.AppendLine("        /// assemblies for which ServiceComposer generated a components provider.");
        builder.AppendLine("        /// </summary>");
        builder.AppendLine("        public static void RegisterReferencedComponents(this global::ServiceComposer.AspNetCore.ViewModelCompositionOptions options)");
        builder.AppendLine("        {");
        foreach (var provider in providers.Distinct().OrderBy(p => p, StringComparer.Ordinal))
        {
            builder.AppendLine($"            options.RegisterComponentsFrom<{provider}>();");
        }
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine("}");

        return builder.ToString();
    }

    static void AppendMethod(StringBuilder builder, string name, List<string> statements)
    {
        builder.AppendLine("        /// <inheritdoc />");
        builder.AppendLine($"        public void {name}(global::ServiceComposer.AspNetCore.ViewModelCompositionOptions options)");
        builder.AppendLine("        {");
        foreach (var statement in statements.OrderBy(s => s, StringComparer.Ordinal))
        {
            builder.AppendLine($"            {statement}");
        }
        builder.AppendLine("        }");
    }
}
